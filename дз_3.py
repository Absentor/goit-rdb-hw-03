import subprocess

script = r'''
import os
os.environ["XDG_RUNTIME_DIR"] = "/tmp/runtime-0"

from sqlalchemy import create_engine, text

engine = create_engine(
    "postgresql://postgres:@/postgres?host=/tmp/hw3_pg"
)

with engine.connect() as conn:
    # Загальна статистика
    print("Статистика числових колонок:")
    for col in ["age", "balance", "duration", "campaign", "pdays", "previous"]:
        row = conn.execute(text(f"""
            SELECT
                MIN({col}),
                PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY {col}),
                PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY {col}),
                PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY {col}),
                MAX({col}),
                AVG({col})
            FROM hw3_bank
        """)).one()
        print(
            f"{col}: min={row[0]}, Q1={row[1]}, "
            f"median={row[2]}, Q3={row[3]}, max={row[4]}, mean={row[5]:.2f}"
        )

    # Кількість потенційних викидів за правилом 1.5 IQR
    for col in ["balance", "duration", "campaign"]:
        q1, q3 = conn.execute(text(f"""
            SELECT
                PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY {col}),
                PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY {col})
            FROM hw3_bank
        """)).one()

        iqr = q3 - q1
        upper = q3 + 1.5 * iqr
        lower = q1 - 1.5 * iqr

        count = conn.execute(text(f"""
            SELECT COUNT(*)
            FROM hw3_bank
            WHERE {col} < :lower OR {col} > :upper
        """), {"lower": lower, "upper": upper}).scalar_one()

        print(
            f"Потенційні викиди {col}: {count}; "
            f"нижня межа={lower:.2f}; верхня межа={upper:.2f}"
        )
'''

